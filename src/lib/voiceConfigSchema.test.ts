import { describe, expect, it } from "vitest";
import { voiceConfigSchema } from "./voiceConfigSchema";

const valid = {
  enabled: true,
  hiring_company: " Acme ",
  question_plan: [{ text: " Tell me about your experience. ", competency_ref: "Engineering", expected_signals: [] }],
  interview_depth: "screening", language: "en", voice: { accent: "us" },
  default_country_code: "+91",
  calling_window: { start: "09:00", end: "21:00", tz: "Asia/Kolkata" },
  retry_policy: { max_attempts: 3, backoff: "exponential" },
  max_concurrent_calls_override: null,
  qualification: { budget_band_pct: 10, ask_location: true, role_facts: [] },
};

describe("voice round validation", () => {
  it("accepts manual or generated questions and trims the submitted text", () => {
    const result = voiceConfigSchema.parse(valid);
    expect(result.hiring_company).toBe("Acme");
    expect(result.question_plan[0].text).toBe("Tell me about your experience.");
  });
  it("blocks saving before questions exist, including deleting every question", () => {
    const result = voiceConfigSchema.safeParse({ ...valid, question_plan: [] });
    expect(result.success).toBe(false);
    if (!result.success) expect(result.error.issues[0].message).toContain("Generate questions");
  });
  it.each([
    { text: "  " }, { competency_ref: " " }, { expected_signals: [" "] },
    { weight: 0 }, { weight: 6 },
  ])("rejects incomplete questions: %j", (change) => {
    expect(voiceConfigSchema.safeParse({ ...valid, question_plan: [{ ...valid.question_plan[0], ...change }] }).success).toBe(false);
  });
  it("allows Hindi wording to be generated by the server on save", () => {
    expect(voiceConfigSchema.safeParse({ ...valid, language: "hi", question_plan: [{ ...valid.question_plan[0], text_hi: "" }] }).success).toBe(true);
  });
  it.each([
    { hiring_company: " " }, { hiring_company: null }, { language: "other" },
    { interview_depth: "other" }, { voice: { accent: "other" } },
    { default_country_code: "91" }, { default_country_code: "+999" },
    { default_country_code: "abc+91" },
    { retry_policy: { max_attempts: 0, backoff: "fixed" } },
    { retry_policy: { max_attempts: 1.5, backoff: "fixed" } },
    { retry_policy: { max_attempts: 3, backoff: "other" } },
    { max_concurrent_calls_override: 0 }, { max_concurrent_calls_override: 1.5 },
  ])("rejects invalid settings: %j", (change) => {
    expect(voiceConfigSchema.safeParse({ ...valid, ...change }).success).toBe(false);
  });
  it.each([
    { budget_cap: -1 }, { budget_band_pct: -1 }, { budget_band_pct: 101 },
    { budget_band_pct: Number.NaN }, { budget_cap: Infinity },
    { distance_threshold_km: -1 }, { role_facts: [" "] }, { work_model: "other" },
    { work_model: "onsite", job_city: " " },
    { work_model: "hybrid", ask_location: false, relocation_required: true },
  ])("rejects invalid qualification settings: %j", (qualification) => {
    expect(voiceConfigSchema.safeParse({ ...valid, qualification }).success).toBe(false);
  });
  it.each([
    { start: "" }, { start: "25:00" }, { end: "21:99" },
    { end: "09:00" }, { tz: "invalid/timezone" },
  ])("rejects invalid calling windows: %j", (change) => {
    expect(voiceConfigSchema.safeParse({ ...valid, calling_window: { ...valid.calling_window, ...change } }).success).toBe(false);
  });
  it("supports overnight calling windows", () => {
    expect(voiceConfigSchema.safeParse({ ...valid, calling_window: { ...valid.calling_window, start: "22:00", end: "06:00" } }).success).toBe(true);
  });
  it("accepts valid numeric boundaries and optional budget and translation fields", () => {
    expect(voiceConfigSchema.safeParse({ ...valid, qualification: { budget_cap: null, budget_band_pct: 100, distance_threshold_km: 0, work_model: "remote" } }).success).toBe(true);
    expect(voiceConfigSchema.safeParse({ ...valid, qualification: { work_model: "onsite", job_city: " Bengaluru " } }).success).toBe(true);
  });
});
